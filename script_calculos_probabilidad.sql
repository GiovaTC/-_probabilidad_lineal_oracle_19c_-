CREATE TABLE calculos_probabilidad (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    casos_favorables  NUMBER(12) NOT NULL,
    casos_posibles    NUMBER(12) NOT NULL,
    probabilidad      NUMBER(12,8) NOT NULL,
    clasificacion     VARCHAR2(40) NOT NULL,
    pendiente         NUMBER(12,8) NOT NULL,
    intercepto        NUMBER(12,8) NOT NULL,
    fecha_registro    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT chk_casos_favorables
        CHECK (casos_favorables >= 0),
    CONSTRAINT chk_casos_posibles
        CHECK (casos_posibles > 0),
    CONSTRAINT chk_favorables_menor
        CHECK (casos_favorables <= casos_posibles),
    CONSTRAINT chk_probabilidad
        CHECK (probabilidad BETWEEN 0 AND 1)
);

COMMIT;

SELECT id, casos_favorables, casos_posibles, probabilidad, clasificacion, pendiente, intercepto, fecha_registro
FROM calculos_probabilidad ORDER BY id DESC;
